// Generates supabase/seed/demo.sql (LOCAL DEVELOPMENT ONLY) from src/lib/demo/cases.ts:
// one hospital, test staff + family accounts, and the demo cases with their bill lines.
// Run: npm run seed:gen
// For a hosted demo: DEMO_PASSWORD=<new> DEMO_SEED_OUT=supabase/seed/demo.deploy.sql tsx scripts/gen-demo-seed.ts
// (that output is gitignored so the deployment's password never lands in the repo).
import { mkdirSync, writeFileSync } from "node:fs";
import { demoCases } from "../src/lib/demo/cases";
import { DEMO_PASSWORD as LOCAL_PASSWORD } from "./demo-accounts";

const DEMO_PASSWORD = process.env.DEMO_PASSWORD || LOCAL_PASSWORD;
const OUT = process.env.DEMO_SEED_OUT || "supabase/seed/demo.sql";


const HOSPITAL = "11111111-1111-4111-8111-111111111111";
const ACCOUNTS = [
  { id: "22222222-2222-4222-8222-000000000001", email: "desk@bima.test", role: "desk", hospital: true },
  { id: "22222222-2222-4222-8222-000000000002", email: "manager@bima.test", role: "manager", hospital: true },
  { id: "22222222-2222-4222-8222-000000000003", email: "family@bima.test", role: "family", hospital: false },
] as const;
const FAMILY_CASE = "BA-24117";

const q = (v: string | number | boolean | null | undefined) =>
  v === null || v === undefined ? "null" : typeof v === "string" ? `'${v.replace(/'/g, "''")}'` : String(v);
const uuid = (prefix: string, n: number) => `${prefix}-0000-4000-8000-${String(n).padStart(12, "0")}`;

const out: string[] = ["-- GENERATED by scripts/gen-demo-seed.ts — local development only.", "begin;"];

for (const a of ACCOUNTS) {
  out.push(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, raw_app_meta_data, raw_user_meta_data, created_at, updated_at, confirmation_token, email_change, email_change_token_new, recovery_token)
values ('00000000-0000-0000-0000-000000000000', ${q(a.id)}, 'authenticated', 'authenticated', ${q(a.email)}, extensions.crypt(${q(DEMO_PASSWORD)}, extensions.gen_salt('bf')), now(), '{"provider":"email","providers":["email"]}', '{}', now(), now(), '', '', '', '');`,
    `insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)
values (gen_random_uuid(), ${q(a.id)}, ${q(a.id)}, jsonb_build_object('sub', ${q(a.id)}, 'email', ${q(a.email)}), 'email', now(), now(), now());`,
  );
}

const cases = demoCases();
out.push(`insert into hospitals (id, name, rohini_id, differential_billing) values (${q(HOSPITAL)}, ${q(cases[0].hospital.name)}, 'DEMO-ROHINI-001', true);`);

for (const a of ACCOUNTS) {
  // the handle_new_user trigger already created a family row; promote staff
  out.push(
    `update users set role = '${a.role}', hospital_id = ${a.hospital ? q(HOSPITAL) : "null"} where id = ${q(a.id)};`,
  );
}

cases.forEach((c, ci) => {
  const policyId = uuid("33333333", ci + 1);
  const caseId = uuid("44444444", ci + 1);
  const p = c.policy;
  const cap = (r: typeof p.roomCap | undefined) =>
    !r || r.type === "none" ? ["'none'", "null"] : r.type === "fixed" ? ["'fixed'", q(r.perDay)] : ["'percent_si'", q(r.percent)];
  const [rt, rv] = cap(p.roomCap);
  const [it, iv] = cap(p.icuCap);
  out.push(
    `insert into policies (id, hospital_id, insurer, tpa, policy_ref_alias, sum_insured, room_cap_type, room_cap_value, icu_cap_type, icu_cap_value, consumables_addon, sub_limits)
values (${q(policyId)}, ${q(HOSPITAL)}, ${q(p.insurer)}, ${q(p.tpa)}, ${q(p.policyRefAlias)}, ${p.sumInsured}, ${rt}, ${rv}, ${it}, ${iv}, ${p.consumablesAddon}, ${q(JSON.stringify(p.subLimits ?? {}))});`,
  );
  // demo timestamps are relative to "now" so the SLA clocks are live after every reset
  const ago = (iso?: string) => (iso ? `now() - interval '${Math.round((Date.now() - Date.parse(iso)) / 60000)} minutes'` : "null");
  const family = c.id === FAMILY_CASE ? q(ACCOUNTS[2].id) : "null";
  out.push(
    `insert into cases (id, hospital_id, policy_id, family_user_id, case_ref, patient_alias, status, is_package_billing, differential_billing, admitted_at, discharge_requested_at, room_rent_per_day, room_days, created_by)
values (${q(caseId)}, ${q(HOSPITAL)}, ${q(policyId)}, ${family}, ${q(c.id)}, ${q(c.patientAlias)}, 'auditing', ${c.isPackageBilling}, ${c.hospital.differentialBilling ? "null" : "false"}, ${ago(c.admittedAt)}, ${ago(c.dischargeRequestedAt)}, ${c.roomRentPerDay}, ${c.roomDays}, ${q(ACCOUNTS[0].id)});`,
  );
  c.items.forEach((it, li) => {
    out.push(
      `insert into bill_items (hospital_id, case_id, line_no, description, department, quantity, unit_rate, amount, tpa_deducted, ocr_confidence, suggested_list)
values (${q(HOSPITAL)}, ${q(caseId)}, ${li + 1}, ${q(it.description)}, '${it.department}', ${it.quantity}, ${q(it.unitRate)}, ${it.amount}, ${it.tpaDeducted}, ${q(it.ocrConfidence)}, ${it.suggestedList ? `'${it.suggestedList}'` : "null"});`,
    );
  });
});

out.push("commit;", "");
mkdirSync("supabase/seed", { recursive: true });
writeFileSync(OUT, out.join("\n"));
console.log(`wrote ${OUT}: ${cases.length} cases, ${ACCOUNTS.length} accounts`);
